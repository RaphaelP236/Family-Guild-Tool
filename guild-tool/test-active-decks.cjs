const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const code = fs.readFileSync(__dirname + '/src/worker.js', 'utf8');
const start = code.indexOf('function mergeDeckCacheRow(');
const end = code.indexOf('function deckCacheErrorRow(', start);
const context = {isDefenceDeckName: name => /def/i.test(name)};
vm.createContext(context);
vm.runInContext(code.slice(start, end), context);
const {deckCacheRow: row, mergeDeckCacheRow: merge} = context;
const initial = row('Player', '1', {hash:'off1',deck_name:'Fast'});
const defence = merge(initial, row('Player','1',{hash:'def1',deck_name:'DEF Slow'}), 'now');
assert.equal(defence.offence_hash,'off1');
assert.equal(defence.defence_hash,'def1');
assert.equal(defence.active_hash,'def1');
const offence = merge(defence, row('Player','1',{hash:'off2',deck_name:'Fast 2'}), 'now');
assert.equal(offence.offence_hash,'off2');
assert.equal(offence.defence_hash,'def1');
assert.equal(offence.active_hash,'off2');
const failed = merge(offence,{name:'Player',user_id:'1',error:'Fetch failed'},'now');
assert.equal(failed.active_hash,'off2');
assert.equal(failed.offence_hash,'off2');
assert.equal(failed.defence_hash,'def1');
assert.equal(context.normalizeDeckCacheRow({hash:'legacy'}).active_hash,'');
console.log('Active deck cache checks passed');
